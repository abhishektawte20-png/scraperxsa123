// Generates core/agentSpec.js from docs/rovo-agent-json-output-block.txt, so the
// text pasted into the agent and the text the extension's "Copy prompt" sends
// can never drift apart. Run: node scripts/build-agent-spec.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function render() {
  const text = readFileSync(path.join(root, "docs/rovo-agent-json-output-block.txt"), "utf8").replace(/\r\n/g, "\n").trimEnd();
  return `"use strict";

/* GENERATED by scripts/build-agent-spec.mjs from docs/rovo-agent-json-output-block.txt. Do not edit by hand. */
(() => {
  globalThis.SXRTS = globalThis.SXRTS || {};
  globalThis.SXRTS.agentSpec = {
    DOMAIN_TOKEN: "<the domain you were given>",
    DATE_TOKEN: "<today's date as DD Mon YYYY>",
    TEXT: ${JSON.stringify(text)}
  };
})();
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, "core/agentSpec.js"), render());
  console.log("core/agentSpec.js written");
}
